#Единицы массы пронумерованы следующим образом 1 - килограмм, 2 - милиграмм, 3 - грамм, 4 - тонна, 5 - центнер. Дан номер единицы массы (целое число в диапозоне 1-5) и масса тела в этих единицах (вещественное число). Найти массу тела в килограммах.
while True:
    try:
        unit = int(input("Введите номер единицы массы (1 - килограмм, 2 - милиграмм, 3 - грамм, 4 - тонна, 5 - центнер): "))
        if unit < 1 or unit > 5:
            print("Ошибка: введите число от 1 до 5")
            continue
        mass = int(input("Введите массу тела в выбранных единицах: "))
        break
    except ValueError:
        print("Ошибка: введите корректные числа")
if unit == 1:
    print("Масса тела в килограммах:", mass)
elif unit == 2:
    print("Масса тела в килограммах:", mass / 1000000)
elif unit == 3:
    print("Масса тела в килограммах:", mass / 1000)
elif unit == 4:
    print("Масса тела в килограммах:", mass * 1000)
elif unit == 5:
    print("Масса тела в килограммах:", mass * 100)